#!/usr/bin/env python3
"""Write src/i18n/plurals_data.rs from CLDR's cardinal plural rules.

    curl -sSfLO https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/cldr-core/supplemental/plurals.json
    python3 scripts/cldr-plurals.py plurals.json

The rules are CLDR's (Unicode License v3, the notice is at the top of the
file written). Each is kept whole, samples and all: the evaluator reads the
condition, and the tests hold it to every sample CLDR gives.
"""
import json
import sys

ORDER = ["zero", "one", "two", "few", "many", "other"]


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(path):
    data = json.load(open(path, encoding="utf-8"))["supplemental"]
    version = data["version"]["_cldrVersion"]
    rules = data["plurals-type-cardinal"]
    out = [
        "// Generated by scripts/cldr-plurals.py from CLDR "
        + version
        + "'s cardinal plural rules. Do not edit.",
        "//",
        "// Copyright © 1991-2025 Unicode, Inc. Unicode License v3: permission is",
        "// granted to use, copy, modify and distribute the Data Files, provided",
        "// this notice appears with them. https://www.unicode.org/license.txt",
        "",
        "/// The CLDR release the rules are from.",
        "pub const CLDR_VERSION: &str = " + rust_str(version) + ";",
        "",
        "/// Each locale's rules, by category, in CLDR's order; `other` has no",
        "/// condition, only samples.",
        "pub const RULES: &[(&str, &[(&str, &str)])] = &[",
    ]
    for locale in sorted(rules):
        cats = rules[locale]
        pairs = []
        for cat in ORDER:
            rule = cats.get("pluralRule-count-" + cat)
            if rule is not None:
                pairs.append("(" + rust_str(cat) + ", " + rust_str(rule.strip()) + ")")
        out.append("    (" + rust_str(locale) + ", &[" + ", ".join(pairs) + "]),")
    out.append("];")
    open("src/i18n/plurals_data.rs", "w", encoding="utf-8").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
