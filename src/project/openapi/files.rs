//! The files `wf api sync` writes for a service kept in `apis`: its
//! groups and types, printed from its spec, each opening with the marker;
//! and how they differ from what is on disk — what `wf api check` and
//! `N07` report.

use std::path::{Path, PathBuf};

use crate::base::vfs::Vfs;
use crate::diagnostics::error::{Result, WebFluentError};
use crate::project::config::project::ApiSource;
use crate::project::openapi::{self, Imported};
use crate::syntax::parser::{Declaration, Program};

/// The first line of every file `sync` writes.
pub fn marker(spec: &str) -> String {
    format!("// Code generated by `wf api sync` from {spec}. DO NOT EDIT.")
}

/// Whether `text` is a file `sync` wrote.
pub fn is_generated(text: &str) -> bool {
    text.starts_with("// Code generated by `wf api sync`")
}

/// One file `sync` writes, by its path in the project.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct File {
    pub path: String,
    pub text: String,
}

/// What `sync` would write for a service.
#[derive(Debug)]
pub struct Generated {
    pub files: Vec<File>,
    pub warnings: Vec<String>,
    pub imported: Imported,
}

/// How a file on disk differs from what `sync` writes.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Change {
    Added(String),
    Changed(String),
    Removed(String),
}

impl Change {
    pub fn path(&self) -> &str {
        match self {
            Change::Added(p) | Change::Changed(p) | Change::Removed(p) => p,
        }
    }
}

fn config_error(message: String) -> WebFluentError {
    WebFluentError::config(message)
}

/// What `sync` writes for `name`, every file read through `vfs`.
///
/// # Errors
///
/// When the spec leaves the project, is missing, or cannot be read.
pub fn generate(
    vfs: &dyn Vfs,
    project: &Path,
    name: &str,
    source: &ApiSource,
) -> Result<Generated> {
    for (what, path) in [("spec", &source.spec), ("out", &source.out)] {
        if !crate::base::vfs::stays_inside(path) {
            return Err(config_error(format!(
                "`apis.{name}.{what}` is `{path}`, outside the project: name a path inside it"
            )));
        }
    }
    let at = project.join(&source.spec);
    let text = vfs.read_to_string(&at).map_err(|e| {
        config_error(format!(
            "`apis.{name}.spec` names `{}`, which cannot be read: {e}",
            source.spec
        ))
    })?;
    let imported = openapi::read(&text, &source.spec, &source.skip)?;
    let generated_dir = format!("{}/generated", source.out.trim_end_matches('/'));
    let head = marker(&source.spec);
    let mut files = Vec::new();
    let write = |file: String, program: &Program, files: &mut Vec<File>| -> Result<()> {
        let body = crate::syntax::print::file_text(program);
        let text = format!("{head}\n\n{body}");
        // What the printer writes reads back as written, or it is a bug.
        let text = crate::syntax::fmt::format_source(&text, &file)?;
        files.push(File { path: file, text });
        Ok(())
    };
    for group in &imported.groups {
        let decl = openapi::group_decl(name, group, crate::base::span::Span::dummy());
        let stem = if group.name == "types" {
            "types-group"
        } else {
            group.name.as_str()
        };
        write(
            format!("{generated_dir}/{stem}.wf"),
            &Program {
                declarations: vec![Declaration::Api(decl)],
            },
            &mut files,
        )?;
    }
    if !imported.declarations.is_empty() {
        write(
            format!("{generated_dir}/types.wf"),
            &Program {
                declarations: imported.declarations.clone(),
            },
            &mut files,
        )?;
    }
    files.sort_by(|a, b| a.path.cmp(&b.path));
    Ok(Generated {
        files,
        warnings: imported.warnings.clone(),
        imported,
    })
}

/// What `sync` would change on disk, read through `vfs`.
///
/// # Errors
///
/// What [`generate`] returns, and a file in `generated/` without the
/// marker, which `sync` would not touch.
pub fn changes(
    vfs: &dyn Vfs,
    project: &Path,
    name: &str,
    source: &ApiSource,
) -> Result<(Generated, Vec<Change>)> {
    let generated = generate(vfs, project, name, source)?;
    let dir = project.join(&source.out).join("generated");
    let mut out = Vec::new();
    for file in &generated.files {
        let at = project.join(&file.path);
        match vfs.read_to_string(&at) {
            Ok(text) if text == file.text => {}
            Ok(text) if !is_generated(&text) => return Err(hand_written(&file.path)),
            Ok(_) => out.push(Change::Changed(file.path.clone())),
            Err(_) => out.push(Change::Added(file.path.clone())),
        }
    }
    let mut on_disk: Vec<PathBuf> = vfs.read_dir(&dir).unwrap_or_default();
    on_disk.sort();
    for at in on_disk {
        let rel = relative(project, &at);
        if generated.files.iter().any(|f| f.path == rel) || vfs.is_dir(&at) {
            continue;
        }
        let text = vfs.read_to_string(&at).unwrap_or_default();
        if !is_generated(&text) {
            return Err(hand_written(&rel));
        }
        out.push(Change::Removed(rel));
    }
    Ok((generated, out))
}

fn hand_written(path: &str) -> WebFluentError {
    config_error(format!(
        "`{path}` is in a folder `wf api sync` owns, and it does not open with the marker `// Code generated by `wf api sync``: it was not written by sync, so it is left alone. Move what it says to `service.wf` or a file of your own, then delete it"
    ))
}

pub(crate) fn relative(project: &Path, at: &Path) -> String {
    at.strip_prefix(project)
        .unwrap_or(at)
        .to_string_lossy()
        .replace('\\', "/")
}

/// `N07`: a kept service whose files `sync` would change — the spec moved
/// on since they were written. Read through `vfs`, for `wf check`.
pub fn stale_services(
    vfs: &dyn Vfs,
    project: &Path,
    apis: &std::collections::BTreeMap<String, ApiSource>,
) -> Vec<(String, String)> {
    let mut out = Vec::new();
    for (name, source) in apis {
        match changes(vfs, project, name, source) {
            Ok((_, changes)) if changes.is_empty() => {}
            Ok((_, changes)) => out.push((
                name.clone(),
                format!(
                    "`{name}`'s files are behind `{}`: `wf api sync {name}` would change {}",
                    source.spec,
                    changes
                        .iter()
                        .map(|c| format!("`{}`", c.path()))
                        .collect::<Vec<_>>()
                        .join(", ")
                ),
            )),
            Err(e) => out.push((name.clone(), format!("`{name}` cannot be synced: {e}"))),
        }
    }
    out
}
